-- 056_v3_view_column_order.sql -- og_num first, and columns grouped by output, in the v3 mito
-- and draft views.
--
-- Written 2026-10-19, during the Phase R test window. Supersedes the column order of the views
-- in 051_v3_mitogenome.sql and 052_v3_draft_genome.sql. The joins are otherwise unchanged.
--
-- Why. 051 and 052 copied the old tables' column order into v3.mitogenome_data and
--   v3.draft_genomes. That order records when each column was added to the base table, not what
--   it belongs to: depth, annotation checks and gene lengths were mixed in with each other, and
--   og_num was missing (mitogenome_data) or column 77 (draft_genomes). Every view now opens with
--   og_num, the sample and row identifiers and nominal_species_id, then one block per process or
--   output, in pipeline order:
--     mitogenome_data   assembly, depth and coverage, annotation (summary, gene content, gene
--                       order, lineage, MITOS, integrity, curation), then genes: rRNA, each
--                       protein-coding gene beside its _trans, tRNA
--     draft_genomes     fastp (raw, filter, filtered), GenomeScope (each _min beside its pair;
--                       genome size last), Tiara, contamination, BUSCO, Merqury, gfastats,
--                       submission
--   The same rule applies to mitogenome_submission_view, v_mito_annotation_genes (generated by
--   rebuild_mito_gene_views()), v_genome_size_comparison and v_draft_genome_status.
--
-- Columns no longer shown (owner request, 2026-10-19):
--   - draft_genomes: the six DepthSizer columns. The tool is retired (owner decision 12);
--     v3.draft_depthsizer keeps its 701 frozen rows, and public.draft_genomes keeps the columns
--     until R.6 archives it.
--   - mitogenome_submission_view: avg_coverage, avg_base_coverage (still in mitogenome_data).
--   At R.6 these views become public's, so these are dropped columns for that merge, like the
--   17 in plan §4.3. Searched 2026-10-19: no reader in the four sibling repositories outside the
--   decommissioned OceanOmics-Database/SS/ importer. OceanGenom_Web is not cloned here and is
--   checked at R.6.
--
-- og_num comes from public.sample (one definition of it, as in 046) wherever the view reaches a
--   sample. The draft views keep draft_genome.og_num, which check_draft compares with public;
--   the two agree. Every new sample join is on og_id, a NOT NULL FK to sample's PK, so it cannot
--   add or drop rows; the verify block checks the row counts.
--
-- Why DROP and CREATE, not CREATE OR REPLACE: OR REPLACE may only append columns. Dropping loses
--   grants and comments, so both are restored and checked below. No CASCADE: on 2026-10-19
--   nothing depended on any v3 view (pg_depend); if something does by the time this runs, the
--   DROP fails loudly.
--
-- check_mito() and check_draft() are replaced. Their mitogenome_submission_view and
--   v_genome_size_comparison comparisons were SELECT * EXCEPT ALL, which is positional and would
--   break on the new order; they now name public's columns in both arms. The draft_genomes and
--   submission-view comparisons lose only the columns the views no longer show.
--
-- Read these views by column name, never by position.
--
-- Replay: drops and recreates the same objects, so a crash-recovery replay is harmless.
--
-- Revert: sql/revert/056_v3_view_column_order_revert.sql restores 051's and 052's orders.

