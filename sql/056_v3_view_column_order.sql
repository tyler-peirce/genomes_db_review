-- Grants and verify -------------------------------------------------------------------------

GRANT SELECT ON v3.mitogenome_data, v3.mitogenome_submission_view, v3.v_mito_annotation_genes,
                v3.draft_genomes, v3.v_genome_size_comparison, v3.v_draft_genome_status TO readonly;
GRANT SELECT ON v3.mitogenome_data, v3.draft_genomes TO oceangenom_web;

DO $verify$
DECLARE
  r record;
BEGIN
  FOR r IN SELECT 'check_mito' AS fn, * FROM v3.check_mito()
           UNION ALL SELECT 'check_draft', * FROM v3.check_draft() LOOP
    IF r.problems <> 0 THEN
      RAISE EXCEPTION '056 check failed: %: % (%)', r.fn, r.check_name, r.problems;
    END IF;
  END LOOP;

  FOR r IN
    SELECT v.view_name, v.n_cols,
           (SELECT count(*) FROM information_schema.columns c
             WHERE c.table_schema = 'v3' AND c.table_name = v.view_name) AS got_cols,
           (SELECT c.column_name FROM information_schema.columns c
             WHERE c.table_schema = 'v3' AND c.table_name = v.view_name AND c.ordinal_position = 1) AS first_col
    FROM (VALUES ('mitogenome_data', 104), ('mitogenome_submission_view', 23),
                 ('v_mito_annotation_genes', 63), ('draft_genomes', 98),
                 ('v_genome_size_comparison', 12), ('v_draft_genome_status', 17)) AS v (view_name, n_cols)
  LOOP
    IF r.first_col IS DISTINCT FROM 'og_num' OR r.got_cols <> r.n_cols THEN
      RAISE EXCEPTION '056: v3.% has % columns starting with %; expected % starting with og_num',
        r.view_name, r.got_cols, r.first_col, r.n_cols;
    END IF;
    IF NOT has_table_privilege('readonly', 'v3.' || r.view_name, 'SELECT') THEN
      RAISE EXCEPTION '056: readonly lost SELECT on v3.%', r.view_name;
    END IF;
  END LOOP;

  IF NOT has_table_privilege('oceangenom_web', 'v3.mitogenome_data', 'SELECT')
     OR NOT has_table_privilege('oceangenom_web', 'v3.draft_genomes', 'SELECT') THEN
    RAISE EXCEPTION '056: oceangenom_web lost SELECT on mitogenome_data or draft_genomes';
  END IF;

  FOR r IN SELECT c.view_name, c.n,
                  (xpath('/row/n/text()', query_to_xml(format('SELECT count(*) AS n FROM v3.%I', c.view_name),
                                                       false, true, '')))[1]::text::bigint AS now_n
           FROM v056_row_counts c LOOP
    IF r.now_n <> r.n THEN
      RAISE EXCEPTION '056: v3.% has % rows, had %', r.view_name, r.now_n, r.n;
    END IF;
  END LOOP;
END
